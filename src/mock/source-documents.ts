export function getSourceDocumentById(id: string): SourceDocument | undefined {
  return sourceDocuments.find((doc) => doc.id === id)
}

export function getFieldSlotsForDocumentPage(documentId: string, pageNumber: number): DocumentFieldSlot[] {
  return documentFieldSlots.filter((slot) => slot.documentId === documentId && slot.pageNumber === pageNumber)
}

export function getFieldSlotById(id: string): DocumentFieldSlot | undefined {
  return documentFieldSlots.find((slot) => slot.id === id)
}
